//! Generated-kernel bank for width-three main continuations.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use cs::gkr_compiler::GKRCircuitArtifact;
use field::proth120::Proth120;

use super::continuation::compile_continuations_with_model;
use super::main_continuation_window::{
    lower_main_continuation_window_program, MAIN_CONTINUATION_WINDOW_SHAPE_DEFINED_BITS,
};
use crate::ElementModel;

/// `(compiled shape mask, minimum blocks per SM)`, sorted by mask.
///
/// The fused executor uses a separate bound because all nine selector warps share a block.
pub const MAIN_CONTINUATION_WINDOW_KERNEL_BANK: [(u16, u32); 7] = [
    (0x00, 4),
    (0x01, 4),
    (0x03, 4),
    (0x07, 4),
    (0x13, 4),
    (0x17, 4),
    (0x1f, 4),
];

/// Shape covering every continuation instruction, used for source partitions.
pub const MAIN_CONTINUATION_WINDOW_UNIVERSAL_MASK: u16 =
    MAIN_CONTINUATION_WINDOW_SHAPE_DEFINED_BITS;
/// Number of compiled shape entries in each continuation kernel family.
pub const MAIN_CONTINUATION_WINDOW_KERNEL_COUNT: usize = MAIN_CONTINUATION_WINDOW_KERNEL_BANK.len();
/// Threads per block for split publication/evaluation kernels.
pub const MAIN_CONTINUATION_WINDOW_BLOCK_THREADS: u32 = 96;
/// One warp per selector pair in the fused tile-owning executor.
pub const MAIN_CONTINUATION_WINDOW_FUSED_THREADS: u32 = 288;
pub const MAIN_CONTINUATION_WINDOW_FUSED_MIN_BLOCKS: u32 = 2;

const GENERATED_HEADER: &str =
    "// @generated by generate_main_continuation_window_production; do not edit.";
const MANIFEST_HEADER_NAME: &str = "main_continuation_window_manifest.cuh";
const FUSED_UNIT_NAME: &str = "main_continuation_window_fused.cu";

/// Repo-relative directory containing the generated native bank.
pub const MAIN_CONTINUATION_WINDOW_GENERATED_NATIVE_DIR: &str =
    "gpu/gkr/native/gkr/backward/main_continuation_window/generated";
/// Repo-relative path of the generated Rust kernel declarations and dispatch table.
pub const MAIN_CONTINUATION_WINDOW_GENERATED_KERNELS: &str =
    "gpu/gkr/src/backward/main_continuation/generated_kernels.rs";

pub const PR_MAIN_CONTINUATION_MASKS: &[u8] = &[0x01, 0x03, 0x07, 0x1f];
pub const PR_MAIN_CONTINUATION_MIN_BLOCKS: u32 = 4;
pub const PR_MAIN_CONTINUATION_GENERATED_NATIVE_DIR: &str =
    "gpu/gkr/native/gkr/proth120/backward/main_continuation_window";
pub const PR_MAIN_CONTINUATION_GENERATED_MANIFEST: &str =
    "gpu/gkr/src/proth120/backward/main_continuation_window_manifest.rs";
const PR_GENERATED_HEADER: &str =
    "// @generated by generate_main_continuation_window_production --field proth120; do not edit.";
const PR_CMAKE_NAME: &str = "CMakeLists.txt";

/// Repository root, resolved independently of the process working directory.
pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("resolve repository root from CARGO_MANIFEST_DIR")
        .to_path_buf()
}

pub fn main_continuation_window_kernel_symbol(mask: u16, min_blocks: u32) -> String {
    format!("ab_gkr_bwd_main_cont_window3_shape_{mask:02x}_b{min_blocks}_kernel")
}

pub fn main_continuation_window_x01_kernel_symbol(mask: u16, min_blocks: u32) -> String {
    format!("ab_gkr_bwd_main_cont_window3_shape_{mask:02x}_b{min_blocks}_x01_kernel")
}

pub fn main_continuation_window_translation_unit_name(mask: u16) -> String {
    format!("main_continuation_window_shape_{mask:02x}.cu")
}

fn fused_symbol(mask: u16, x01: bool) -> String {
    format!(
        "ab_gkr_main_cont_fused_{mask:02x}_b{MAIN_CONTINUATION_WINDOW_FUSED_MIN_BLOCKS}{}",
        if x01 { "_x01" } else { "" }
    )
}

fn render_fused_translation_unit() -> String {
    let mut out = format!("{GENERATED_HEADER}\n#include \"../fused_executor.cuh\"\n\nnamespace airbender::gkr::backward {{\n\n");
    for (mask, _) in MAIN_CONTINUATION_WINDOW_KERNEL_BANK {
        for x01 in [false, true] {
            out.push_str(&format!("AB_GKR_MAIN_CONT_DEFINE_FUSED({}, {mask:#04x}, {MAIN_CONTINUATION_WINDOW_FUSED_MIN_BLOCKS}, {x01}, false);\n", fused_symbol(mask, x01)));
        }
    }
    out.push_str(&format!("\nstatic_assert(BWD_MAIN_CONT_FUSED_THREADS == {MAIN_CONTINUATION_WINDOW_FUSED_THREADS}, \"fused continuation geometry drift\");\n\n}} // namespace airbender::gkr::backward\n"));
    out
}

pub fn main_continuation_window_generated_artifacts() -> Vec<(String, String)> {
    let mut artifacts = vec![(
        format!("{MAIN_CONTINUATION_WINDOW_GENERATED_NATIVE_DIR}/{MANIFEST_HEADER_NAME}"),
        render_main_continuation_window_manifest(),
    )];
    for (mask, min_blocks) in MAIN_CONTINUATION_WINDOW_KERNEL_BANK {
        artifacts.push((
            format!(
                "{MAIN_CONTINUATION_WINDOW_GENERATED_NATIVE_DIR}/{}",
                main_continuation_window_translation_unit_name(mask)
            ),
            render_main_continuation_window_translation_unit(mask, min_blocks),
        ));
    }
    artifacts.push((
        format!("{MAIN_CONTINUATION_WINDOW_GENERATED_NATIVE_DIR}/{FUSED_UNIT_NAME}"),
        render_fused_translation_unit(),
    ));
    artifacts.push((
        MAIN_CONTINUATION_WINDOW_GENERATED_KERNELS.to_owned(),
        render_main_continuation_window_kernels(),
    ));
    artifacts
}

fn render_main_continuation_window_manifest() -> String {
    format!(
        "{GENERATED_HEADER}\n\
         #pragma once\n\
         \n\
         namespace airbender::gkr::backward {{\n\
         \n\
         inline constexpr unsigned BWD_MAIN_CONTINUATION_WINDOW_KERNEL_COUNT = {};\n\
         \n\
         }} // namespace airbender::gkr::backward\n",
        MAIN_CONTINUATION_WINDOW_KERNEL_COUNT,
    )
}

pub fn render_main_continuation_window_translation_unit(mask: u16, min_blocks: u32) -> String {
    let symbol = main_continuation_window_kernel_symbol(mask, min_blocks);
    let x01_symbol = main_continuation_window_x01_kernel_symbol(mask, min_blocks);
    format!(
        "{GENERATED_HEADER}\n\
         #include \"../executor.cuh\"\n\
         #include \"{MANIFEST_HEADER_NAME}\"\n\
         \n\
         namespace airbender::gkr::backward {{\n\
         \n\
         AB_GKR_BWD_MAIN_CONT_WINDOW_DEFINE_KERNEL({symbol}, {mask:#04x}, {min_blocks});\n\
         AB_GKR_BWD_MAIN_CONT_WINDOW_DEFINE_X01_KERNEL({x01_symbol}, {mask:#04x}, {min_blocks});\n\
         \n\
         static_assert(BWD_MAIN_CONTINUATION_WINDOW_KERNEL_COUNT == {MAIN_CONTINUATION_WINDOW_KERNEL_COUNT}, \"shape_{mask:02x} continuation-window manifest drift\");\n\
         \n\
         }} // namespace airbender::gkr::backward\n"
    )
}

fn render_main_continuation_window_kernels() -> String {
    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push_str("\n\n");
    out.push_str(
        "use era_cudart::{cuda_kernel_declaration, cuda_kernel_signature_arguments_and_function};\n\n",
    );
    out.push_str("use super::binding::MainContinuationWindowLaunchBinding;\n\n");
    out.push_str(
        "/// Shape covering every continuation instruction, used for source partitions.\n",
    );
    out.push_str(&format!(
        "pub(crate) const MAIN_CONTINUATION_WINDOW_UNIVERSAL_MASK: u16 = {MAIN_CONTINUATION_WINDOW_UNIVERSAL_MASK:#04x};\n\n"
    ));
    out.push_str("/// Threads per block for split publication/evaluation kernels.\n");
    out.push_str(&format!(
        "pub(crate) const MAIN_CONTINUATION_WINDOW_BLOCK_THREADS: u32 = {MAIN_CONTINUATION_WINDOW_BLOCK_THREADS};\n\n"
    ));
    out.push_str(&format!("pub(crate) const MAIN_CONTINUATION_WINDOW_FUSED_THREADS: u32 = {MAIN_CONTINUATION_WINDOW_FUSED_THREADS};\n\n"));
    out.push_str(&format!("pub(crate) const MAIN_CONTINUATION_WINDOW_FUSED_MIN_BLOCKS: u32 = {MAIN_CONTINUATION_WINDOW_FUSED_MIN_BLOCKS};\n\n"));
    out.push_str("cuda_kernel_signature_arguments_and_function!(\n");
    out.push_str("    pub(crate) GkrBwdMainContinuationWindow3,\n");
    out.push_str("    desc: MainContinuationWindowLaunchBinding,\n");
    out.push_str(");\n\n");
    out.push_str("/// One generated continuation-window entry point.\n");
    out.push_str("pub(crate) struct MainContinuationWindowKernelEntry {\n");
    out.push_str("    pub mask: u16,\n");
    out.push_str("    pub symbol: GkrBwdMainContinuationWindow3Signature,\n");
    out.push_str("    pub x01_symbol: GkrBwdMainContinuationWindow3Signature,\n");
    out.push_str("    pub fused_symbol: GkrBwdMainContinuationWindow3Signature,\n");
    out.push_str("    pub fused_x01_symbol: GkrBwdMainContinuationWindow3Signature,\n");
    out.push_str("}\n\n");
    for (mask, min_blocks) in MAIN_CONTINUATION_WINDOW_KERNEL_BANK {
        out.push_str(&format!(
            "cuda_kernel_declaration!(\n    pub(crate) {}(desc: MainContinuationWindowLaunchBinding)\n);\n",
            main_continuation_window_kernel_symbol(mask, min_blocks)
        ));
        out.push_str(&format!(
            "cuda_kernel_declaration!(\n    pub(crate) {}(desc: MainContinuationWindowLaunchBinding)\n);\n",
            main_continuation_window_x01_kernel_symbol(mask, min_blocks)
        ));
        for x01 in [false, true] {
            out.push_str(&format!("cuda_kernel_declaration!(\n    pub(crate) {}(desc: MainContinuationWindowLaunchBinding)\n);\n", fused_symbol(mask, x01)));
        }
    }
    out.push('\n');
    out.push_str(&format!(
        "pub(crate) const MAIN_CONTINUATION_WINDOW_KERNELS: [MainContinuationWindowKernelEntry; {}] = [\n",
        MAIN_CONTINUATION_WINDOW_KERNEL_COUNT
    ));
    for (mask, min_blocks) in MAIN_CONTINUATION_WINDOW_KERNEL_BANK {
        let symbol = main_continuation_window_kernel_symbol(mask, min_blocks);
        let x01_symbol = main_continuation_window_x01_kernel_symbol(mask, min_blocks);
        out.push_str("    MainContinuationWindowKernelEntry {\n");
        out.push_str(&format!("        mask: {mask:#04x},\n"));
        out.push_str(&format!("        symbol: {symbol},\n"));
        out.push_str(&format!("        x01_symbol: {x01_symbol},\n"));
        out.push_str(&format!(
            "        fused_symbol: {},\n",
            fused_symbol(mask, false)
        ));
        out.push_str(&format!(
            "        fused_x01_symbol: {},\n",
            fused_symbol(mask, true)
        ));
        out.push_str("    },\n");
    }
    out.push_str("];\n");
    out
}

fn expected_generated_native_entries() -> Vec<String> {
    let mut expected: Vec<String> = MAIN_CONTINUATION_WINDOW_KERNEL_BANK
        .into_iter()
        .map(|(mask, _)| main_continuation_window_translation_unit_name(mask))
        .collect();
    expected.push(MANIFEST_HEADER_NAME.to_owned());
    expected.push(FUSED_UNIT_NAME.to_owned());
    expected.sort();
    expected
}

/// Fail if the generated native directory contains a stale or extra file.
pub fn validate_main_continuation_window_generated_tree(root: &Path) -> Result<(), String> {
    let directory = root.join(MAIN_CONTINUATION_WINDOW_GENERATED_NATIVE_DIR);
    let mut present: Vec<String> = std::fs::read_dir(&directory)
        .map_err(|error| format!("{}: {error}", directory.display()))?
        .map(|entry| {
            entry
                .map_err(|error| error.to_string())
                .map(|entry| entry.file_name().to_string_lossy().into_owned())
        })
        .collect::<Result<_, _>>()?;
    present.sort();
    let expected = expected_generated_native_entries();
    if present != expected {
        return Err(format!(
            "generated native tree differs: present={present:?}, expected={expected:?}"
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cpu_main_continuation_window_manifest_committed_artifacts_are_current() {
        let root = repo_root();
        for (relative, rendered) in main_continuation_window_generated_artifacts() {
            let committed = std::fs::read_to_string(root.join(&relative))
                .unwrap_or_else(|error| panic!("{relative}: {error}"));
            assert_eq!(
                committed, rendered,
                "{relative} is stale; rerun generate_main_continuation_window_production --write"
            );
        }
    }

    #[test]
    fn cpu_main_continuation_window_manifest_generated_tree_has_no_extra_files() {
        validate_main_continuation_window_generated_tree(&repo_root()).unwrap();
    }

    #[test]
    fn pr_bank_is_current() {
        let root = repo_root();
        for (relative, rendered) in
            pr_main_continuation_window_generated_artifacts(PR_MAIN_CONTINUATION_MASKS)
        {
            let committed = std::fs::read_to_string(root.join(&relative))
                .unwrap_or_else(|error| panic!("{relative}: {error}"));
            assert_eq!(
                committed, rendered,
                "{relative} is stale; rerun generate_main_continuation_window_production --field proth120 --write"
            );
        }
        validate_pr_main_continuation_window_generated_tree(&root, PR_MAIN_CONTINUATION_MASKS)
            .unwrap();
    }

    #[test]
    fn pr_manifest_lists_every_mask() {
        let layout: GKRCircuitArtifact<Proth120> = serde_json::from_slice(
            &std::fs::read(repo_root().join(
                "cs/compiled_circuits/unified_reduced_machine_layout_gkr_proth120_2p21.json",
            ))
            .unwrap(),
        )
        .unwrap();
        let masks = pr_main_continuation_masks(&layout).unwrap();
        assert_eq!(masks, PR_MAIN_CONTINUATION_MASKS);
        assert!(masks.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(masks
            .iter()
            .all(|&mask| u16::from(mask) & !MAIN_CONTINUATION_WINDOW_SHAPE_DEFINED_BITS == 0));
    }
}

pub fn pr_main_continuation_kernel_symbol(mask: u8) -> String {
    format!("ab_pr_gkr_bwd_main_cont_{mask:02x}_kernel")
}

fn pr_translation_unit_name(mask: u8) -> String {
    format!("{mask:02x}.cu")
}

pub fn pr_main_continuation_masks(
    layout: &GKRCircuitArtifact<Proth120>,
) -> Result<Vec<u8>, String> {
    let dag = gkr_eval_ir::lower_dag(layout)?;
    let continuations = compile_continuations_with_model(&dag, ElementModel::PROTH120)
        .map_err(|error| format!("Proth120 continuation: {error:?}"))?;
    let mut masks = BTreeSet::new();
    for layer in &continuations.layers {
        let window = lower_main_continuation_window_program(layer)
            .map_err(|error| format!("Proth120 main continuation L{}: {error}", layer.layer))?;
        masks.insert(u8::try_from(window.shape.bits()).expect("continuation shape fits u8"));
    }
    Ok(masks.into_iter().collect())
}

fn render_pr_translation_unit(mask: u8) -> String {
    format!(
        "{PR_GENERATED_HEADER}\n\
         #include \"../main_continuation_executor_pr.cuh\"\n\
         \n\
         namespace airbender::gkr::proth120::backward {{\n\
         \n\
         AB_PR_GKR_BWD_MAIN_CONT_DEFINE_KERNEL({}, {mask:#04x}, {PR_MAIN_CONTINUATION_MIN_BLOCKS});\n\
         \n\
         }} // namespace airbender::gkr::proth120::backward\n",
        pr_main_continuation_kernel_symbol(mask)
    )
}

fn render_pr_cmake(masks: &[u8]) -> String {
    let mut out = format!(
        "# {}\ntarget_sources(gpu_gkr_native PRIVATE\n",
        &PR_GENERATED_HEADER[3..]
    );
    for &mask in masks {
        out.push_str(&format!("        {}\n", pr_translation_unit_name(mask)));
    }
    out.push_str(")\n");
    out
}

fn render_pr_manifest(masks: &[u8]) -> String {
    let list = masks
        .iter()
        .map(|mask| format!("{mask:#04x}"))
        .collect::<Vec<_>>()
        .join(", ");
    let mut out = format!("{PR_GENERATED_HEADER}\n\n");
    out.push_str(
        "use era_cudart::{cuda_kernel_declaration, cuda_kernel_signature_arguments_and_function};\n\n",
    );
    out.push_str(
        "use super::main_continuation::binding::MainContinuationWindowLaunchBindingPr;\n\n",
    );
    out.push_str(&format!(
        "pub const PR_MAIN_CONTINUATION_MASKS: &[u8] = &[{list}];\n\n"
    ));
    out.push_str("cuda_kernel_signature_arguments_and_function!(\n");
    out.push_str("    pub(crate) PrGkrBwdMainContinuationWindow,\n");
    out.push_str("    desc: MainContinuationWindowLaunchBindingPr,\n");
    out.push_str(");\n\n");
    for &mask in masks {
        out.push_str(&format!(
            "cuda_kernel_declaration!(\n    pub(crate) {}(desc: MainContinuationWindowLaunchBindingPr)\n);\n",
            pr_main_continuation_kernel_symbol(mask)
        ));
    }
    out.push('\n');
    out.push_str("pub(crate) struct PrMainContinuationWindowKernelEntry {\n");
    out.push_str("    pub mask: u8,\n");
    out.push_str("    pub symbol: PrGkrBwdMainContinuationWindowSignature,\n");
    out.push_str("}\n\n");
    out.push_str(&format!(
        "pub(crate) const PR_MAIN_CONTINUATION_WINDOW_KERNELS: [PrMainContinuationWindowKernelEntry; {}] = [\n",
        masks.len()
    ));
    for &mask in masks {
        out.push_str("    PrMainContinuationWindowKernelEntry {\n");
        out.push_str(&format!("        mask: {mask:#04x},\n"));
        out.push_str(&format!(
            "        symbol: {},\n",
            pr_main_continuation_kernel_symbol(mask)
        ));
        out.push_str("    },\n");
    }
    out.push_str("];\n");
    out
}

pub fn pr_main_continuation_window_generated_artifacts(masks: &[u8]) -> Vec<(String, String)> {
    let mut artifacts: Vec<(String, String)> = masks
        .iter()
        .map(|&mask| {
            (
                format!(
                    "{PR_MAIN_CONTINUATION_GENERATED_NATIVE_DIR}/{}",
                    pr_translation_unit_name(mask)
                ),
                render_pr_translation_unit(mask),
            )
        })
        .collect();
    artifacts.push((
        format!("{PR_MAIN_CONTINUATION_GENERATED_NATIVE_DIR}/{PR_CMAKE_NAME}"),
        render_pr_cmake(masks),
    ));
    artifacts.push((
        PR_MAIN_CONTINUATION_GENERATED_MANIFEST.to_owned(),
        render_pr_manifest(masks),
    ));
    artifacts
}

pub fn validate_pr_main_continuation_window_generated_tree(
    root: &Path,
    masks: &[u8],
) -> Result<(), String> {
    let directory = root.join(PR_MAIN_CONTINUATION_GENERATED_NATIVE_DIR);
    let mut present: Vec<String> = std::fs::read_dir(&directory)
        .map_err(|error| format!("{}: {error}", directory.display()))?
        .map(|entry| {
            entry
                .map_err(|error| error.to_string())
                .map(|entry| entry.file_name().to_string_lossy().into_owned())
        })
        .collect::<Result<_, _>>()?;
    present.sort();
    let mut expected: Vec<String> = masks
        .iter()
        .map(|&mask| pr_translation_unit_name(mask))
        .collect();
    expected.push(PR_CMAKE_NAME.to_owned());
    expected.sort();
    if present != expected {
        return Err(format!(
            "generated Proth120 native tree differs: present={present:?}, expected={expected:?}"
        ));
    }
    Ok(())
}
