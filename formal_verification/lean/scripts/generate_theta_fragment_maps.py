#!/usr/bin/env python3
"""Generate finite node correspondences. Lean checks each native transition."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "Airbender/Proofs/Keccak"
MODULUS = 2013265921


def selected_values(column, offset, length):
    result = []
    position = 0
    for block in column["blocks"]:
        kind = block["kind"]
        if kind == "affine":
            size = block["length"]
        elif kind == "dense":
            size = len(block["values"])
        elif kind == "periodic":
            size = block["repetitions"] * len(block["values"])
        else:
            raise ValueError(f"unsupported native block: {kind}")
        first, last = max(offset, position), min(offset + length, position + size)
        for i in range(first - position, last - position):
            if kind == "affine":
                value = block["first"] + block["step"] * i
            elif kind == "dense":
                value = block["values"][i]
            else:
                values = block["values"]
                value = values[i % len(values)] + block["stride"] * (i // len(values))
            result.append(value % MODULUS)
        position += size
    if len(result) != length:
        raise ValueError("incomplete native region")
    return result


def literal_nodes(values):
    extent = 16
    while extent < len(values):
        extent *= 16
    layer = values + [0] * (extent - len(values))
    nodes, indices = [], {}
    while len(layer) > 1:
        parents = []
        for start in range(0, len(layer), 16):
            node = tuple(layer[start:start + 16])
            if node not in indices:
                indices[node] = len(nodes)
                nodes.append(node)
            parents.append(indices[node])
        layer = parents
    return nodes, indices, layer[0]


def correspondence(reference, native_indices, shift, high):
    def output(value):
        return value // 2 ** (8 - shift) if high else value * 2 ** shift % 256

    leaf = [native_indices[tuple(output(value) for value in node)] for node in reference]
    pair = [native_indices[tuple(leaf[value] for value in node)] for node in reference]
    byte = [native_indices[tuple(pair[value] for value in node)] for node in reference[:16]]
    root = native_indices[tuple(byte[value] for value in reference[0])]
    return leaf, pair, byte, root


def vector(values):
    return "#v[" + ", ".join(map(str, values)) + "]"


def certificate_module(high, shift):
    kind = "High" if high else "Low"
    suffix = kind.lower()
    column = 4 if high else 3
    mapping = f"thetaFragment{kind}Map{shift}"
    target = f"(thetaRhoXorSplit.columns[{column}])"
    output = f"xorFragment{kind} {shift}"
    def row_property(remaining, node):
        result = f"({output}) (xorByteEntry {node} digit.val)" if remaining == 1 else f"{mapping}.at 1 (xorByteEntry {node} digit.val)"
        return f"{target}.nodes[{mapping}.at {remaining} {node}]? = some (Vector.ofFn fun digit : Fin 16 => {result})"

    leaf_proof = f"(xor_fragment_blocks (fun node => {row_property(1, 'node')}) leaf0 leaf1 leaf2 leaf3)"
    pair_groups = []
    for group in range(4):
        node = "node" if group == 0 else f"({64 * group} + node)"
        parts = " ".join(f"pair{4 * group + part}" for part in range(4))
        pair_groups.append(f"(xor_fragment_small_blocks (fun node => {row_property(2, node)}) {parts})")
    pair_proof = f"(xor_fragment_blocks (fun node => {row_property(2, 'node')})\n      " + "\n      ".join(pair_groups) + ")"
    lines = [
        "-- Generated by scripts/generate_theta_fragment_maps.py. Kernel checks follow.",
        "import Airbender.Proofs.Keccak.SplitThetaFragmentMaps",
        "import Airbender.Data.Setup.Keccak.ThetaRhoXorSplit",
        "", "namespace Airbender.Keccak.Split.Native.Fixed.Proofs",
        "set_option warningAsError true", "set_option maxRecDepth 65536",
        "set_option Elab.async false", "",
    ]
    for level, remaining in [("leaf", 1), ("pair", 2)]:
        for block in range(4 if remaining == 1 else 16):
            base, inner = (64 * block, 0) if remaining == 1 else (64 * (block // 4), 16 * (block % 4))
            node = "node.val" if not inner else f"({inner} + node.val)"
            if base:
                node = f"({base} + {node})"
            size = 64 if remaining == 1 else 16
            expected = f"({output}) (xorByteEntry {node} digit.val)" if remaining == 1 else f"{mapping}.at 1 (xorByteEntry {node} digit.val)"
            lines += [
                f"private theorem {level}{block} : ∀ node : Fin {size},",
                f"    {target}.nodes[{mapping}.at {remaining} {node}]? =",
                f"      some (Vector.ofFn fun digit : Fin 16 => {expected}) := by",
                "  decide +kernel", "",
            ]
    lines += [
        "private theorem byte : ∀ node : Fin 16,",
        f"    {target}.nodes[{mapping}.at 3 node.val]? =",
        f"      some (Vector.ofFn fun digit : Fin 16 => {mapping}.at 2 (xorByteEntry node.val digit.val)) := by", "  decide +kernel", "",
        "private theorem root :",
        f"    {target}.nodes[{mapping}.root]? =",
        f"      some (Vector.ofFn fun digit : Fin 16 => {mapping}.at 3 (xorByteEntry 0 digit.val)) := by",
        "  decide +kernel", "",
        f"/-- Every actual native transition preserves this complete shift-{shift} fragment correspondence. -/",
        f"theorem theta_fragment_{suffix}_certificate{shift} :",
        f"    XorFragmentRefines {target} ({output}) {mapping} := by",
        "  exact xor_fragment_refines_of_rows",
        f"    (target := {target}) (output := {output}) (map := {mapping})",
        f"    {leaf_proof}", f"    {pair_proof}", "    byte root", "",
        "end Airbender.Keccak.Split.Native.Fixed.Proofs", "",
    ]
    return "\n".join(lines)


def generate():
    source = json.loads((ROOT / "artifacts/setup/keccak-theta-rho.json").read_text())
    regions = {table["id"]: table for table in source["tables"]}
    xor = regions[4]
    reference, _, _ = literal_nodes(selected_values(source["columns"][2], xor["offset"], xor["length"]))
    if len(reference) != 256:
        raise ValueError("native byte-XOR graph changed")
    split = regions[58]
    outputs = {}
    maps = [
        "-- Generated by scripts/generate_theta_fragment_maps.py. Kernel checks all correspondences.",
        "import Airbender.Proofs.Keccak.SplitThetaFragmentMap", "",
        "namespace Airbender.Keccak.Split.Native.Fixed.Proofs", "set_option maxRecDepth 65536", "",
    ]
    for high in [False, True]:
        kind = "High" if high else "Low"
        column = 4 if high else 3
        _, indices, _ = literal_nodes(selected_values(source["columns"][column], split["offset"], split["length"]))
        for shift in range(8):
            leaf, pair, byte, root = correspondence(reference, indices, shift, high)
            maps += [
                f"def thetaFragment{kind}Map{shift} : XorFragmentMap where",
                f"  leaf := {vector(leaf)}", f"  pair := {vector(pair)}", f"  byte := {vector(byte)}", f"  root := {root}", "",
            ]
            outputs[TARGET / f"SplitThetaFragment{kind}{shift}.lean"] = certificate_module(high, shift)
    maps += ["end Airbender.Keccak.Split.Native.Fixed.Proofs", ""]
    outputs[TARGET / "SplitThetaFragmentMaps.lean"] = "\n".join(maps)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in generate().items():
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"stale fragment certificate source: {path.relative_to(ROOT)}")
        else:
            path.write_text(expected)
    print("PASS 16 native fragment correspondences" + (" are current" if args.check else " generated"))


if __name__ == "__main__":
    main()
