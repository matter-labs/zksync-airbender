"""The 64 final-XOR queries of the extended-control Blake2s round row (imported lookups 130 to 193): writes
FinalLookups0-7.lean (one module per chaining word, four queries per limb), each query with the honest chunk
values (`RowInput.finalSlot`) and, for quotient entries, the natural identity `field_identity` needs.

Run from cs_formal_verification/lean (no inputs besides the output directory; see README.md):
  python3 -I gen/nonvac/blake2round/final_xor.py slop/Slop/NonVacuous/Blake2RoundSpan
"""
import sys

HEADER = '-- Generated by gen/nonvac/blake2round/final_xor.py (`python3 -I gen/nonvac/blake2round/final_xor.py slop/Slop/NonVacuous/Blake2RoundSpan`); do not edit by hand.\n'


def emit(path, text):
    with open(path, 'w') as out:
        out.write(HEADER + text)

KIND={4:'(Or.inl ⟨rfl, rfl⟩)',19:'(Or.inr (Or.inl ⟨rfl, rfl⟩))',20:'(Or.inr (Or.inr ⟨rfl, rfl⟩))'}
W={4:8,19:7,20:9}
def lookups(i,h):
  L=2*i+h; N=130+4*L
  C=f'(x.state {i}).{"lo" if h==0 else "hi"}'
  F=lambda j: f'x.finalSlot {i} {h} {j}'
  out=[]
  if i<4:
    g1=(i+2)%4; g2=i
    E1=f'(x.diagCall {g1}).{"c2lo" if h==0 else "c2hi"}'
    E2=f'(x.diagCall {g2}).{"a2lo" if h==0 else "a2hi"}'
    # (tag, A, B, Cc, entry tactics for a,b)
    out.append((19, F(0), f'{E1} % 128', F(1), None, None))
    out.append((20, f'{C} / 128', f'{E1} / 128', F(2),
      ('(-15728640)', f'{C} = {F(0)} + 128 * ({C} / 128)'),
      ('(-15728640)', f'{E1} = {E1} % 128 + 128 * ({E1} / 128)')))
    out.append((19, F(1), f'{E2} % 128', F(4), None, ('1', f'{E2} % 256 = {E2} % 128 + 128 * {F(3)}')))
    out.append((20, F(2), f'{E2} / 128', F(5), None,
      ('(-15728640)', f'{E2} + 128 * {F(3)} = {E2} % 256 + 128 * ({E2} / 128)')))
  else:
    g1=(i+3)%4; g2=(i+1)%4
    lo1,hi1,E1=(('xf1','xf2','b2lo') if h==0 else ('xf3','xf0','b2hi'))
    lo2,hi2,E2=(('xe1','xe2','d2lo') if h==0 else ('xe3','xe0','d2hi'))
    G1=f'(x.diagCall {g1})'; G2=f'(x.diagCall {g2})'
    out.append((20, f'{G1}.{lo1}', F(0), F(1), None, None))
    out.append((19, f'{G1}.{hi1}', f'{C} / 512', F(2),
      ('(-3932160)', f'{G1}.{E1} = {G1}.{lo1} + 512 * {G1}.{hi1}'),
      ('(-3932160)', f'{C} = {F(0)} + 512 * ({C} / 512)')))
    out.append((4, f'{G2}.{lo2}', f'{F(1)} % 256', F(4), None, ('1', f'{F(1)} = {F(1)} % 256 + 256 * {F(3)}')))
    out.append((4, f'{G2}.{hi2}', f'{F(3)} + 2 * {F(2)}', F(5),
      ('(-7864320)', f'{G2}.{E2} = {G2}.{lo2} + 256 * {G2}.{hi2}'), 'ring'))
  return N,out
def gen(q):
  words=[q]
  S=[f'''module
public import Slop.NonVacuous.Blake2RoundSpan.FinalEval

@[expose] public section

/-! The final-XOR queries of chaining word {q} (imported lookups {130+8*q} to {130+8*q+7}) hold for the
    honest assignment of valid inputs over BabyBear: four per limb, each a plain XOR of chunks of the chaining limb
    and the two extended words (`RowInput.finalSlot`). -/

namespace Airbender.NonVacuous.Blake2RoundSpan
open Blake2Round.Proofs

variable {{p : Nat}} [Fact p.Prime] (hp : p = 2013265921) {{x : RowInput}} (valid : x.Valid)
include hp valid
''']
  for i in words:
    for h in (0,1):
      N,qs=lookups(i,h)
      calls=sorted({(i+2)%4,i} if i<4 else {(i+3)%4,(i+1)%4})
      for s,(t,A,B,Cc,ea,eb) in enumerate(qs):
        n=N+s
        def ent(e):
          if e is None: return '  · honest_entry'
          if e=='ring': return '  · honest_entry\n    push_cast\n    ring'
          how='from rfl' if ('b2' in e[1] or 'd2' in e[1]) else 'by final_unfold'
          return f'  · honest_entry\n    field_identity {e[0]} (show {e[1]} {how})'
        S.append(f'''private theorem final_lookup_{n} {{L : List (Lookup (ZMod p))}}
    (hL : FlatOperation.lookups (Blake2Round.importedConstraints Blake2Round.setupTable) = L) {{n : Nat}}
    {{hn : n < L.length}} (index : n = {n}) : (L.get ⟨n, hn⟩).Contains (Verification.environment x.assignment) := by
  subst hp
  final_bounds_{'low' if i<4 else 'high'} valid {i} {h} {calls[0]} {calls[1]}
  refine contains_xor hL (Blake2Round.importedConstraints.lookup_{n} _ (query_lt (by decide))) index {KIND[t]}
    (chunkXor_cast (w := {W[t]}) (m := {A}) (n := {B}) (k := {Cc}) (by final_unfold) (by final_unfold) (by final_unfold) (by decide)
      (by final_unfold)) ?_ ?_ ?_ ?_ ?_ ?_
  · honest_entry
{ent(ea)}
{ent(eb)}
  · honest_entry
  · honest_entry
  · honest_entry
''')
  lo=130+8*q
  alts=' ∨ '.join(f'n = {lo+j}' for j in range(8))
  S.append(f'''theorem final_lookups_{q} {{L : List (Lookup (ZMod p))}}
    (hL : FlatOperation.lookups (Blake2Round.importedConstraints Blake2Round.setupTable) = L) (n : Nat)
    (hn : n < L.length) (lower : {lo} ≤ n) (upper : n < {lo+8}) :
    (L.get ⟨n, hn⟩).Contains (Verification.environment x.assignment) := by
  rcases (by omega : {alts}) with
    {' | '.join(['index']*8)}''')
  for j in range(8): S.append(f'  · exact final_lookup_{lo+j} hp valid hL index')
  S.append('\nend Airbender.NonVacuous.Blake2RoundSpan\n')
  return '\n'.join(S)
for q in range(8):
  emit(f'{sys.argv[1]}/FinalLookups{q}.lean', gen(q))
