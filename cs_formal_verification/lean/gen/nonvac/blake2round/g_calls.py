"""The 128 fixed-table queries of the eight G calls of the extended-control Blake2s round row (imported lookups
2 to 129): writes ColumnLookups0-3.lean and DiagonalLookups0-3.lean, one private lemma per query (its entries
evaluate to the call's `GTrace` fields, `column_eq` / `diagonal_eq`) and a dispatcher per call.

Run from cs_formal_verification/lean (no inputs besides the output directory; see README.md):
  python3 -I gen/nonvac/blake2round/g_calls.py proven/Proven/NonVacuous/Blake2RoundSpan
"""
import sys

HEADER = '-- Generated by gen/nonvac/blake2round/g_calls.py (`python3 -I gen/nonvac/blake2round/g_calls.py proven/Proven/NonVacuous/Blake2RoundSpan`); do not edit by hand.\n'


def emit(path, text):
    with open(path, 'w') as out:
        out.write(HEADER + text)

COL=[('carry','8','q0','ka0'),('xor','4','q1'),('carry','8','q2','ka1'),('xor','4','q3'),('xor','20','q4'),('xor','20','q5'),
     ('split','q6'),('split','q7'),('xor','4','q8'),('xor','4','q9'),('carry','8','q10','kb0'),('carry','8','q11','kb1'),
     ('xor','20','q12'),('xor','20','q13'),('xor','19','q14'),('xor','19','q15')]
DIAG=COL[:14]+[('carry','7','q14','kd0'),('carry','7','q15','kd1')]
KIND={'4':'(Or.inl ⟨rfl, rfl⟩)','19':'(Or.inr (Or.inl ⟨rfl, rfl⟩))','20':'(Or.inr (Or.inr ⟨rfl, rfl⟩))','8':'(Or.inl ⟨rfl, rfl⟩)','7':'(Or.inr ⟨rfl, rfl⟩)'}
def gen(diag,k):
  base=(66 if diag else 2)+16*k
  name='diagonal' if diag else 'column'
  trace='diagonalTrace' if diag else 'columnTrace'
  tac='diagonal_eq' if diag else 'column_eq'
  qs=DIAG if diag else COL
  L=[]
  L.append(f'''module
public import Proven.NonVacuous.Blake2RoundSpan.Queries
public import Proven.Blake2Round.{'DiagonalG' if diag else 'ColumnG'}

@[expose] public section

/-! The sixteen fixed-table queries of {name} G call {k} (imported lookups {base} to {base+15}) hold over BabyBear
    when its trace's table facts do (`Blake2Round.Proofs.GTrace.Rows`), for any assignment: one lemma per query,
    whose entries evaluate to the trace's fields (`{tac}`). -/

namespace Airbender.NonVacuous.Blake2RoundSpan
open Blake2Round.Proofs

variable {{p : Nat}} [Fact p.Prime] (hp : p = 2013265921) (w : Nat → ZMod p) (rows : ({trace} {k} w).Rows)
include hp rows
''')
  for j,q in enumerate(qs):
    i=base+j
    lk=f'hL (Blake2Round.importedConstraints.lookup_{i} _ (query_lt (by decide))) index'
    if q[0]=='carry': head=f'contains_carry {lk} {KIND[q[1]]} rows.{q[2]} rows.{q[3]}'
    elif q[0]=='xor': head=f'contains_xor {lk} {KIND[q[1]]} rows.{q[2]}'
    else: head=f'contains_split {lk} rows.{q[1]}'
    L.append(f'''private theorem {name}_lookup_{i} {{L : List (Lookup (ZMod p))}}
    (hL : FlatOperation.lookups (Blake2Round.importedConstraints Blake2Round.setupTable) = L) {{n : Nat}}
    {{hn : n < L.length}} (index : n = {i}) : (L.get ⟨n, hn⟩).Contains (Verification.environment w) := by
  subst hp
  refine {head} ?_ ?_ ?_ ?_ ?_ ?_
  all_goals {tac}
''')
  alts=' ∨ '.join(f'n = {base+j}' for j in range(16))
  pats=' | '.join('index' for j in range(16))
  L.append(f'''theorem {name}_lookups_{k} {{L : List (Lookup (ZMod p))}}
    (hL : FlatOperation.lookups (Blake2Round.importedConstraints Blake2Round.setupTable) = L) (n : Nat)
    (hn : n < L.length) (lower : {base} ≤ n) (upper : n < {base+16}) :
    (L.get ⟨n, hn⟩).Contains (Verification.environment w) := by
  rcases (by omega : {alts}) with
    {pats}''')
  for j in range(16):
    L.append(f'  · exact {name}_lookup_{base+j} hp w rows hL index')
  L.append('\nend Airbender.NonVacuous.Blake2RoundSpan\n')
  return '\n'.join(L)
d=sys.argv[1]
for diag in (False,True):
  for k in range(4):
    nm=('DiagonalLookups' if diag else 'ColumnLookups')+str(k)
    emit(f'{d}/{nm}.lean', gen(diag,k))
