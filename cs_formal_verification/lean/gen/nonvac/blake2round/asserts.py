HEADER = '-- Generated by gen/nonvac/blake2round/asserts.py (`python3 -I gen/nonvac/blake2round/asserts.py slop/Slop/NonVacuous/Blake2RoundSpan`); do not edit by hand.\n'


def emit(path, text):
    with open(path, 'w') as out:
        out.write(HEADER + text)

def flagcol(k):
  if k==0: return 0
  if 124<=k<=136: return 139+(k-124)
  if 137<=k<=152:
    c=(k-137)//4; r=(k-137)%4; return 256+40*c+[12,15,33,35][r]
  if 153<=k<=160:
    c=(k-153)//2; r=(k-153)%2; return 416+30*c+[10,13][r]
  if 161<=k<=176:
    L=k-161; return 539+6*L
  if 177<=k<=219: return 634+3*(k-177)
def tactic(k):
  if k in (0,) or 124<=k<=219:
    col=flagcol(k)
    pre=''
    if 137<=k<=152: pre=f'  have carries := (valid.colCall (k := {(k-137)//4}) (by decide)).carries\n'
    if 153<=k<=160: pre=f'  have carries := (valid.diagCall (k := {(k-153)//2}) (by decide)).carries\n'
    if 161<=k<=176:
      L=k-161; i=L//2; h=L%2
      pre=f'  have slots := (valid.finalSlot_bounds (i := {i}) (h := {h}) (by decide)).{1 if i<4 else 2} (by decide)\n'
    return pre+f'''  have bit : x.column {col} = 0 ∨ x.column {col} = 1 := by bit_value
  simp only [Expression.eval, Verification.environment, RowInput.assignment]
  rcases bit with bit | bit <;> rw [bit] <;> push_cast <;> ring'''
  body='''  simp only [Expression.eval, Verification.environment, RowInput.assignment]
  honest_value
'''
  if k in (1,2,3,107): return body+'  round_cases x'
  if 108<=k<=123: return body+'  final_cases x'
  return body+'  first_round_cases x'
GROUPS={'Control':[0,1,2,3,106,107],'Products':list(range(52,74)),'Chaining':list(range(4,28)),
  'Lanes':list(range(28,52)),'Writeback':list(range(108,137)),'Carries':list(range(137,161)),
  'FinalBits':list(range(161,177)),'BorrowsLow':list(range(177,198)),'BorrowsHigh':list(range(198,220))}
DOC={'Control':'the execute flag, the control word read and written, and its final and first-round flags',
 'Products':'the two mode flags and the twenty round-by-mode products, all zero in the plain mode',
 'Chaining':'the first 24 preparation equations: the chaining words and prepared lanes 0 to 5 (the first round reads the chaining state)',
 'Lanes':'the last 24 preparation equations: prepared lanes 6 to 15 (the first round reads the chaining state and the IV)',
 'Writeback':'the 16 final write-back equations and the 13 control bits',
 'Carries':'the 24 Boolean carries of the G calls',
 'FinalBits':'the 16 Boolean final-XOR bits',
 'BorrowsLow':'the Boolean clock borrows of ports 0 to 20',
 'BorrowsHigh':'the Boolean clock borrows of ports 21 to 42'}
def gen(g):
  idx=GROUPS[g]
  S=[f'''module
public import Slop.NonVacuous.Blake2RoundSpan.AssertEval

@[expose] public section

/-! Imported constraints of an honest round row ({DOC[g]}): each holds for the honest assignment of valid inputs. -/

namespace Airbender.NonVacuous.Blake2RoundSpan

variable {{p : Nat}} [Fact p.Prime] {{x : RowInput}}
''']
  V = '(valid : x.Valid) ' if g in ('Carries', 'FinalBits') else ''
  for k in idx:
    VALID=V
    S.append(f'''private theorem assert_{k} {VALID}{{L : List (Expression (ZMod p))}}
    (hL : FlatOperation.constraints (Blake2Round.importedConstraints (p := p) Blake2Round.setupTable) = L) {{n : Nat}}
    {{hn : n < L.length}} (index : n = {k}) : (L.get ⟨n, hn⟩).eval (Verification.environment x.assignment) = 0 := by
  subst hL index
  rw [Blake2Round.importedConstraints.constraint_{k}]
{tactic(k)}
''')
  # dispatcher: membership in a list of indices
  ranges=[]
  start=idx[0]; prev=idx[0]
  for k in idx[1:]:
    if k!=prev+1: ranges.append((start,prev)); start=k
    prev=k
  ranges.append((start,prev))
  cond=' ∨ '.join(f'({a} ≤ n ∧ n ≤ {b})' for a,b in ranges)
  alts=' ∨ '.join(f'n = {k}' for k in idx)
  S.append(f'''theorem asserts_{g} {V}{{L : List (Expression (ZMod p))}}
    (hL : FlatOperation.constraints (Blake2Round.importedConstraints (p := p) Blake2Round.setupTable) = L) (n : Nat)
    (hn : n < L.length) (range : {cond}) :
    (L.get ⟨n, hn⟩).eval (Verification.environment x.assignment) = 0 := by
  rcases (by omega : {alts}) with
    {' | '.join(['index']*len(idx))}''')
  for k in idx: S.append(f'  · exact assert_{k} {"valid " if g in ("Carries", "FinalBits") else ""}hL index')
  S.append('\nend Airbender.NonVacuous.Blake2RoundSpan\n')
  return '\n'.join(S)
for g in GROUPS:
  emit(f'{sys.argv[1]}/Asserts{g}.lean', gen(g))
