#!/usr/bin/env bash
# Builds the guest in both variants and writes build/{app,app_mop}.{elf,bin,dis,sym,sha256} plus the Lean copies of
# the images, lean/image/{Image,ImageMop}.lean. app: BabyBear in plain Rust; app_mop: cargo feature `mop` (field
# opcodes, as the real verifier).
set -euo pipefail
cd "$(dirname "$0")"
BIN="$(rustc --print sysroot)/lib/rustlib/$(rustc -vV | sed -n 's/^host: //p')/bin"
OUT=../build; mkdir -p $OUT

# image NAME LEAN_NAMESPACE CARGO_ARGS...
image() {
local name=$1 ns=$2; shift 2
local tdir=target/$name
cargo build --release --quiet --target-dir $tdir "$@"
cp $tdir/riscv32i-unknown-none-elf/release/app $OUT/$name.elf
"$BIN/llvm-objcopy" -O binary $OUT/$name.elf $OUT/$name.bin
"$BIN/llvm-objdump" -d --no-show-raw-insn -M no-aliases $OUT/$name.elf > $OUT/$name.dis
"$BIN/llvm-nm" -n -S $OUT/$name.elf > $OUT/$name.sym
sha256sum $OUT/$name.bin | tee $OUT/$name.sha256

LEAN=../lean/image/$ns.lean; mkdir -p "$(dirname $LEAN)"
{
  echo "/-! GENERATED by rust/build.sh from build/$name.bin — do not edit."
  echo "    sha256 $(cut -d' ' -f1 $OUT/$name.sha256) -/"
  echo "namespace $ns"
  echo ""
  echo "set_option maxRecDepth 100000 in"
  echo "/-- The flat image, loaded at address 0 (Airbender ROM). -/"
  echo "def bytes : Array (BitVec 8) := #["
  od -An -v -tx1 $OUT/$name.bin | sed 's/^ *//; s/ *$//; /^$/d; s/  */ /g; s/\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/  /'
  echo "]"
  echo ""
  echo "/-! Symbols from llvm-nm, under fixed names (Rust's mangled names change from build to build). -/"
  awk 'function name(n) {
         if (n ~ /3app4main$/) return "main"
         if (n ~ /boot_sequence4init$/) return "init"
         if (n ~ /33zksync_os_finish_success_extended$/) return "finish_success_extended"
         if (n ~ /24zksync_os_finish_success$/) return "finish_success"
         if (n ~ /^_R/) return ""
         return n }
       NF == 4 && $2 != "00000000" && ($3 == "T" || $3 == "t") && name($4) != "" {
         printf "def %s : Nat := 0x%s\ndef %s_size : Nat := 0x%s\n", name($4), $1, name($4), $2 }
       NF == 4 && $2 != "00000000" && ($3 == "B" || $3 == "b") && $4 !~ /^\./ {
         printf "def %s : Nat := 0x%s  -- .bss (RAM, zero at start)\ndef %s_size : Nat := 0x%s\n", $4, $1, $4, $2 }
       NF == 4 && $2 != "00000000" && ($3 == "R" || $3 == "r") {
         n = $4; if (n ~ /^_R/) sub(/.*3app[0-9]+/, "", n);
         printf "def %s : Nat := 0x%s  -- .rodata (in RAM after init), size 0x%s\ndef %s_size : Nat := 0x%s\n", n, $1, $2, n, $2 }
       NF == 4 && $4 ~ /^_(sirodata|srodata|erodata|sidata|sdata|edata|sbss|ebss|sstack|estack)$/ {
         printf "def %s : Nat := 0x%s  -- linker symbol\n", substr($4, 2), $1 }' $OUT/$name.sym
  # the program has finished: the self-jump (`jal zero, .`) that ends zksync_os_finish_success_extended
  awk '$2 == "jal" && $3 == "zero," && $4 == "0x" substr($1, 1, length($1) - 1) {
         printf "def halt : Nat := 0x%s  -- `jal zero, .`: the program has finished\n", substr($1, 1, length($1) - 1) }' $OUT/$name.dis
  echo ""
  echo "end $ns"
} > $LEAN
}

image app Image
image app_mop ImageMop --features mop
