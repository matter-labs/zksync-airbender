"""Generate slop/Slop/Equiv/Checks.lean from Airbender.MachineChecks (human/HumanSail/Checks.lean): one theorem per
commented group of conjuncts (each `decide +kernel`, checked independently), and `machine_checks` assembled from
them. Run from lean/: python3 gen/machine_checks.py"""
import re

src = open('human/HumanSail/Checks.lean').read()
body = src[src.index('def MachineChecks : Prop :=') + len('def MachineChecks : Prop :='):src.index('end Airbender')]
groups, cur = [], None
for line in body.split('\n'):
    st = line.strip()
    if not st:
        continue
    if st.startswith('--'):
        cur = []
        groups.append((st[2:].strip(), cur))
        continue
    cur.append(line.rstrip())

out = ['import HumanSail.Checks', '',
       '/-! `Airbender.MachineChecks`: each conjunct evaluated by the Lean kernel on the Sail model, in groups (one',
       'theorem each, so they are checked independently). Generated by lean/gen/machine_checks.py. -/', '',
       'open Sail SailRV32 SailRV32.Functions Human', '', 'namespace Airbender', '']
projs = []
for i, (comment, lines) in enumerate(groups):
    m = re.match(r'^(.*?)(\s*∧)?(\s*--.*)?$', lines[-1])
    lines[-1] = m[1] + (m[3] or '')
    name = f'checks{i + 1}'
    out += [f'/-- {comment[0].upper() + comment[1:]}. -/', f'theorem {name} :']
    out += ['    ' + l.strip() for l in lines]
    out += ['    := by decide +kernel', '']
    for j in range(len(lines)):
        projs.append(name + '.2' * j + ('.1' if j < len(lines) - 1 else ''))
rows, row = [], '  exact ⟨'
for p in projs:
    if len(row) + len(p) + 2 > 116:
        rows.append(row.rstrip())
        row = '    '
    row += p + ', '
rows.append(row.rstrip().rstrip(',') + '⟩')
out += ['theorem machine_checks : MachineChecks := by'] + rows + ['', 'end Airbender']
open('slop/Slop/Equiv/Checks.lean', 'w').write('\n'.join(out) + '\n')
